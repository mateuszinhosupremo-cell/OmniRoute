// Generates pack/Mark5_BP/scripts/suit/hud_protocol.js and tools/hud_protocol.resolved.json
// from tools/hud_protocol.json (single source of truth for the HUD data string).
// Usage: node tools/gen_protocol.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "tools/hud_protocol.json"), "utf8"));

let offset = Buffer.byteLength(spec.header, "utf8");
const fields = spec.fields.map((f) => {
  const out = { name: f.name, type: f.type, width: f.width, start: offset, end: offset + f.width };
  offset += f.width;
  return out;
});
const total = offset;

writeFileSync(
  join(root, "tools/hud_protocol.resolved.json"),
  JSON.stringify({ header: spec.header, totalBytes: total, fields }, null, 2) + "\n"
);

const js = `// GENERATED by tools/gen_protocol.mjs from tools/hud_protocol.json — do not edit by hand.
// Mark V HUD data string layout. Widths are UTF-8 BYTES. See encodeHud() in ./hud.js.

export const HUD_HEADER = ${JSON.stringify(spec.header)};
export const HUD_TOTAL_BYTES = ${total};

/** @type {ReadonlyArray<{name:string,type:"char"|"digits"|"text",width:number,start:number,end:number}>} */
export const HUD_FIELDS = Object.freeze([
${fields.map((f) => `  Object.freeze(${JSON.stringify(f)}),`).join("\n")}
]);
`;
const jsPath = join(root, "pack/Mark5_BP/scripts/suit/hud_protocol.js");
mkdirSync(dirname(jsPath), { recursive: true });
writeFileSync(jsPath, js);
console.log(`fields=${fields.length} totalBytes=${total}`);
for (const f of fields) console.log(`${f.name.padEnd(16)} [${f.start}, ${f.end}) ${f.type}`);
